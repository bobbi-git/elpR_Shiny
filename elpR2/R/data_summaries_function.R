  if("Vegetation Class" %in% names(daily_site_summary)){
    # group by strata instead of site and get means per week
    Event_weekly_means_veg <- daily_site_summary %>%
      dplyr::group_by(`Vegetation Class`,WeekDate) %>%
      dplyr::summarise(
        MeanDailyEvents = if(all(is.na(`total_Events`))) NA_real_
        else mean(`total_Events`, na.rm=TRUE),
        sdDailyEvents = if(all(is.na(`total_Events`))) NA_real_
        else sd(`total_Events`, na.rm=TRUE),
        n = dplyr::n(),
        seDailyEvents = sdDailyEvents/sqrt(n),
        maxDailyEvents = if(all(is.na(`total_Events`))) NA_real_
        else max(`total_Events`, na.rm=TRUE),
        minDailyEvents = if(all(is.na(`total_Events`))) NA_real_
        else min(`total_Events`, na.rm=TRUE),
        sumEvents = if(all(is.na(`total_Events`))) NA_real_
        else sum(`total_Events`, na.rm=TRUE),
        sumEventsNight = if(all(is.na(`night_total`))) NA_real_
        else sum(`night_total`, na.rm=TRUE),
        meanEventsNight = if(all(is.na(`night_total`))) NA_real_
        else mean(`night_total`, na.rm=TRUE),
        sdEventsNight = if(all(is.na(`night_total`))) NA_real_
        else sd(`night_total`, na.rm=TRUE),
        seEventsNight = sdEventsNight/sqrt(n),
        PropNightEvents = round(sumEventsNight/sumEvents, digit = 3),
        SumEventsPerDaysSampled = round(sumEvents/n,digit=3),
        SumNightEventsPerDaysSampled = round(sumEventsNight/n,digit=3)
      )
    # combine with complete weeks
    complete_weeks_veg <- expand.grid(
      WeekDate = week_range,
      `Vegetation Class` = unique(Event_weekly_means_veg$`Vegetation Class`))
    Event_weekly_means_veg_complete <- left_join(complete_weeks_veg, Event_weekly_means_veg, by = c("Vegetation Class","WeekDate"))

    # plot
    EventWklyVeg<-ggplot(as.data.frame(Event_weekly_means_veg_complete), aes(x=as.Date(WeekDate),y=MeanDailyEvents))+
      geom_line(na.rm = TRUE)+
      geom_point()+
      geom_errorbar(aes(ymin = MeanDailyEvents - seDailyEvents,
                        ymax = MeanDailyEvents + seDailyEvents),
                    width = 0.2)+
      #stat_summary(fun.data=mean_cl_normal)+
      geom_smooth(method='lm', se = TRUE, size = 1.2, linetype = "dashed", aes(color = `Vegetation Class`))+
      theme_bw() +
      facet_wrap(~`Vegetation Class`)+
      scale_x_date(date_breaks = "6 month", date_labels = "%b-%Y") +
      scale_y_continuous(
        #name = "Mean Daily Events per Week",
        limits = c(0, max(Event_weekly_means_veg_complete$MeanDailyEvents +
                            max(Event_weekly_means_veg_complete$seDailyEvents, na.rm = TRUE), na.rm = TRUE)+5),
        breaks = seq(0, max(Event_weekly_means_veg_complete$MeanDailyEvents +
                              Event_weekly_means_veg_complete$seDailyEvents, na.rm = TRUE)+5,
                     by = 50),
        minor_breaks = NULL,
        expand = c(0,0))+  # This removes the space below 0
      theme(axis.text.x=element_text(angle=60, hjust=1),plot.title = element_text(hjust = 0.5),
            panel.grid.major = element_line(colour="white", size=0.5))+
      labs(title = "Mean Daily Events per Week by Vegetation Class",
           x = "Week (month-year)",
           y = "Mean Daily Events per Week (±SE)")

    write.table(Event_weekly_means_veg_complete,paste0(parent_dir,"/data_summaries/summary_tables/",proj_dep_name,
                                                       "_Mean_Daily_Events_VegClass_Weekly_Summaries.txt"),
                sep='\t',na="",col.names=TRUE,row.names=FALSE,
                quote=FALSE, append=FALSE)
  }


  #### MONTHLY SUMMARIES ####
  # add number of days sampled per month
  # add number of Events per sampled date value
  # plot proportion of night Events per month

  ##### mean daily per month by site #####
  Event_monthly_means_site <- daily_site_summary %>%
    dplyr::group_by(Year,Month,Site) %>%
    dplyr::summarise(
      MeanDailyEvents = if(all(is.na(total_Events))) NA_real_
      else mean(total_Events, na.rm=TRUE),
      sdDailyEvents = if(all(is.na(total_Events))) NA_real_
      else sd(total_Events, na.rm=TRUE),
      n = n(),
      seDailyEvents = sdDailyEvents/sqrt(n),
      maxDailyEvents = if(all(is.na(total_Events))) NA_real_
      else max(total_Events, na.rm=TRUE),
      minDailyEvents = if(all(is.na(total_Events))) NA_real_
      else min(total_Events, na.rm=TRUE),
      sumEvents = if(all(is.na(total_Events))) NA_real_
      else sum(total_Events, na.rm=TRUE),
      sumNightEvents = if(all(is.na(night_total))) NA_real_
      else sum(night_total,na.rm=TRUE),
      meanNightEvents = if(all(is.na(night_total))) NA_real_
      else mean(night_total,na.rm=TRUE),
      proportionNightEvents = sumNightEvents/sumEvents
    )
  sum(Event_monthly_means_site$sumEvents, na.rm=T) #36236
  Event_monthly_means_site$`Year-Month` <- as.Date(paste(Event_monthly_means_site$Year, Event_monthly_means_site$Month, "01", sep = "-"))
  # create a grouping variable for consecutive months
  Event_monthly_means_site <- Event_monthly_means_site %>%
    arrange(Site, `Year-Month`) %>%
    dplyr::group_by(Site) %>%
    mutate(month_group = cumsum(c(TRUE, diff(as.numeric(`Year-Month`)) > 31))) %>%
    ungroup()
  write.table(Event_monthly_means_site,
              paste0(parent_dir,"/data_summaries/summary_tables/",proj_dep_name,"_Events_ZeroDays_soundExcluded_3randDaysOnly_MonthlyMean_Site.txt"),
              sep='\t',na="",col.names=TRUE,row.names=FALSE, quote=FALSE, append=FALSE)

  # plot monthly means by site
  Event_monthly_means_site_plot <- ggplot(as.data.frame(Event_monthly_means_site),aes(x=`Year-Month`,y=MeanDailyEvents))+
    geom_line(aes(group = month_group))+
    #geom_point()+
    stat_summary(fun.data=mean_cl_normal)+
    facet_wrap(~Site)+
    scale_x_date(date_breaks = "6 months",
                 date_labels = "%b-%Y")+
    scale_y_continuous(trans = "pseudo_log")+
    theme(axis.text.x = element_text(angle = 60, hjust = 1),
          plot.title = element_text(hjust = 0.5),
          panel.grid.major = element_line(colour = "white"),
          panel.grid.minor = element_blank())+
    labs(title = "Average Number of Events per Day per Month by Site",
         x = "Date (Month-Year)",
         y = "Log-Transformed Average Number of Events per Day (+/- SE)")

  ##### average Events per day by month #####
  Event_monthly_means <- daily_site_summary %>%
    dplyr::group_by(Year,Month) %>%
    dplyr::summarise(
      MeanDailyEvents = if(all(is.na(total_Events))) NA_real_
      else mean(total_Events, na.rm=TRUE),
      sdDailyEvents = if(all(is.na(total_Events))) NA_real_
      else sd(total_Events, na.rm=TRUE),
      n = n(),
      seDailyEvents = sdDailyEvents/sqrt(n),
      maxDailyEvents = if(all(is.na(total_Events))) NA_real_
      else max(total_Events, na.rm=TRUE),
      minDailyEvents = if(all(is.na(total_Events))) NA_real_
      else min(total_Events, na.rm=TRUE),
      sumEvents = if(all(is.na(total_Events))) NA_real_
      else sum(total_Events, na.rm=TRUE),
      sumNightEvents = if(all(is.na(night_total))) NA_real_
      else sum(night_total,na.rm=TRUE),
      meanNightEvents = if(all(is.na(night_total))) NA_real_
      else mean(night_total,na.rm=TRUE),
      proportionNightEvents = sumNightEvents/sumEvents
    )
  sum(Event_monthly_means$sumEvents, na.rm=T) #36236
  Event_monthly_means$`Year-Month` <- as.Date(paste(Event_monthly_means$Year, Event_monthly_means$Month, "01", sep = "-"))
  write.table(Event_monthly_means,
              paste0(parent_dir,"/data_summaries/summary_tables/",proj_dep_name,"_Events_ZeroDays_soundExcluded_3randDaysOnly_MonthlyMean.txt"),
              sep='\t',na="",col.names=TRUE,row.names=FALSE, quote=FALSE, append=FALSE)

  # Create complete time series
  all_dates <- seq.Date(
    from = min(Event_monthly_means$`Year-Month`, na.rm = TRUE),
    to = max(Event_monthly_means$`Year-Month`, na.rm = TRUE),
    by = "1 month"
  )
  # Create complete dataset with all months
  monthly_means_complete <- tibble(`Year-Month` = all_dates) %>%
    left_join(Event_monthly_means, by = "Year-Month")
  # add days since start to table for lm
  monthly_means_complete <- monthly_means_complete %>%
    mutate(days_since_start = as.numeric(`Year-Month` - min(`Year-Month`)))
  # plot monthly means
  Event_monthly_means_plot <- ggplot() +
    geom_errorbar(data = monthly_means_complete,
                  aes(x = `Year-Month`,
                      ymin = MeanDailyEvents - seDailyEvents,
                      ymax = MeanDailyEvents + seDailyEvents),
                  width = 10,
                  size = 0.5,
                  alpha = 0.7) +
    geom_line(data = monthly_means_complete,
              aes(x = `Year-Month`, y = MeanDailyEvents),
              alpha = 0.5) +
    geom_point(data = monthly_means_complete,
               aes(x = `Year-Month`, y = MeanDailyEvents),
               color = "blue",
               size = 2) +
    geom_smooth(data = monthly_means_complete,
                aes(x = `Year-Month`, y = MeanDailyEvents),
                method = "lm",
                se = TRUE,
                color = "blue") +
    scale_x_date(date_breaks = "6 months",
                 date_labels = "%b-%Y") +
    theme_bw() +
    theme(axis.text.x = element_text(angle = 60, hjust = 1),
          plot.title = element_text(hjust = 0.5),
          panel.grid.major = element_line(colour = "gray90"),
          panel.grid.minor = element_blank()) +
    labs(title = "Average Daily Events per Month",
         subtitle = "Blue points show monthly averages (± SE)",
         x = "Month-Year",
         y = "Average Daily Events (± SE)")

  # Fit the linear model for monthly means
  lm_fit <- lm(MeanDailyEvents ~ days_since_start, data = monthly_means_complete)
  print(cat("Monthly Means Linear Regression Summary:\n"))
  print(summary(lm_fit))
  stargazer(lm_fit,
            type = "text",
            title = "Monthly Means Linear Regression Summary",
            covariate.labels = "Time",
            report = "vc*spt",
            out = paste(parent_dir,"/data_summaries/summary_tables/",proj_dep_name,"_monthly_means_regression_summary.txt",sep=""))

  ##### mean daily per month by stratum #####
  if("Strata" %in% names(daily_site_summary)){
    Event_monthly_means_stratum <- daily_site_summary %>%
      dplyr::group_by(Year,Month,Strata) %>%
      dplyr::summarise(
        MeanDailyEvents = if(all(is.na(total_Events))) NA_real_
        else mean(total_Events, na.rm=TRUE),
        sdDailyEvents = if(all(is.na(total_Events))) NA_real_
        else sd(total_Events, na.rm=TRUE),
        n = n(),
        seDailyEvents = sdDailyEvents/sqrt(n),
        maxDailyEvents = if(all(is.na(total_Events))) NA_real_
        else max(total_Events, na.rm=TRUE),
        minDailyEvents = if(all(is.na(total_Events))) NA_real_
        else min(total_Events, na.rm=TRUE),
        sumEvents = if(all(is.na(total_Events))) NA_real_
        else sum(total_Events, na.rm=TRUE),
        sumNightEvents = if(all(is.na(night_total))) NA_real_
        else sum(night_total,na.rm=TRUE),
        meanNightEvents = if(all(is.na(night_total))) NA_real_
        else mean(night_total,na.rm=TRUE),
        proportionNightEvents = sumNightEvents/sumEvents
      )
    sum(Event_monthly_means_stratum$sumEvents, na.rm=T) #36236
    Event_monthly_means_stratum$`Year-Month` <- as.Date(paste(Event_monthly_means_stratum$Year, Event_monthly_means_stratum$Month, "01", sep = "-"))
    write.table(Event_monthly_means_stratum,
                paste0(parent_dir,"/data_summaries/summary_tables/",proj_dep_name,"_PNNN_Events_ZeroDays_soundExcluded_3randDaysOnly_MonthlyMean_Stratum.txt"),
                sep='\t',na="",col.names=TRUE,row.names=FALSE, quote=FALSE, append=FALSE)
  }

  # plot monthly means per stratum
  if("Strata" %in% names(daily_site_summary)){
    # First create a grouping variable for consecutive months
    Event_monthly_means_stratum <- Event_monthly_means_stratum %>%
      arrange(Strata, `Year-Month`) %>%
      group_by(Strata) %>%
      mutate(month_group = cumsum(c(TRUE, diff(as.numeric(`Year-Month`)) > 31))) %>%
      ungroup()

    Event_monthly_means_stratum_plot <- ggplot(as.data.frame(Event_monthly_means_stratum),
                                                aes(x=`Year-Month`,y=MeanDailyEvents))+
      geom_errorbar(aes(ymin=MeanDailyEvents-seDailyEvents,
                        ymax=MeanDailyEvents+seDailyEvents),
                    width=.1) +
      # Modified geom_line to use the grouping variable
      geom_line(aes(group = month_group), color = "dark blue")+
      geom_point()+
      stat_summary(fun.data=mean_cl_normal)+
      geom_smooth(method='lm', aes(color = Strata)) +
      scale_color_viridis_d()+
      facet_wrap(~Strata)+
      scale_x_date(date_breaks = "6 months",
                   date_labels = "%b-%Y")+
      scale_y_continuous()+
      theme(axis.text.x = element_text(angle = 60, hjust = 1),
            plot.title = element_text(hjust = 0.5),
            panel.grid.major = element_line(colour = "white"),
            panel.grid.minor = element_blank())+
      labs(title = "Average Number of Events per Day per Month by Stratum",
           x = "Date (Month-Year)",
           y = "Average Number of Events per Day (+/- SE)")
  }

  # plot monthly means with stratum together (note that month 38 has 0 detections. Check sound check for this month)
  if("Strata" %in% names(daily_site_summary)){
    # Create complete time series
    all_dates <- seq.Date(
      from = min(Event_monthly_means_stratum$`Year-Month`, na.rm=TRUE),
      to = max(Event_monthly_means_stratum$`Year-Month`, na.rm=TRUE),
      by = "month"
    )
    all_strata <- unique(Event_monthly_means_stratum$Strata)
    complete_grid <- expand.grid(
      `Year-Month` = all_dates,
      Strata = all_strata
    ) %>% as_tibble()
    Event_monthly_complete <- left_join(
      complete_grid,
      Event_monthly_means_stratum,
      by = c("Year-Month", "Strata")
    )

    # Create the plot with complete data
    Event_monthly_means_stratum_plot_overlay <- ggplot(as.data.frame(Event_monthly_complete),
                                                        aes(x=`Year-Month`, y=MeanDailyEvents, color=Strata))+
      geom_errorbar(aes(ymin=MeanDailyEvents-seDailyEvents,
                        ymax=MeanDailyEvents+seDailyEvents),
                    width=.1, alpha=0.5) +
      geom_line() +
      geom_point()+
      stat_summary(fun.data=mean_cl_normal)+
      geom_smooth(method='lm', aes(fill = Strata), alpha = 0.2) +
      scale_color_viridis_d() +
      scale_fill_viridis_d() +
      scale_x_date(date_breaks = "6 months",
                   date_labels = "%b-%Y")+
      scale_y_continuous()+
      theme_bw() +
      theme(axis.text.x = element_text(angle = 60, hjust = 1),
            plot.title = element_text(hjust = 0.5),
            panel.grid.major = element_line(colour = "gray90"),
            panel.grid.minor = element_blank(),
            legend.position = "top")+
      labs(title = "Average Number of Events per Day per Month by Stratum",
           x = "Date (Month-Year)",
           y = "Average Number of Events per Day (+/- SE)")
  }

  # Regression model monthly means per strata
  if("Strata" %in% names(daily_site_summary)){
    # convert dates to a numeric value (days since start)
    Event_monthly_complete <- Event_monthly_complete %>%
      mutate(days_since_start = as.numeric(`Year-Month` - min(`Year-Month`)))
    # Create models using the same date format as ggplot
    strata_models <- Event_monthly_complete %>%
      group_by(Strata) %>%
      nest() %>%
      mutate(
        model = map(data, ~lm(MeanDailyEvents ~ days_since_start, data = .x))
      )
    model_list <- strata_models$model
    names(model_list) <- strata_models$Strata
    stargazer(model_list,
              type = "text",
              title = "Regression Results by Stratum",
              column.labels = strata_models$Strata,
              intercept.bottom = FALSE,
              report = "vc*spt",
              out = paste0(parent_dir,"/data_summaries/summary_tables/",proj_dep_name,"_stratum_regression_results.txt"))
  }


  #### SAVE PLOTS ####
  # List all default plots
  save_list <- list(
    total_plot = events_hrly_Date_plot,
    night_day_plot = events_hrly_nightday_plot,
    hourly_plot = events_hr_plot,

    daily_plot_site = Events_daily_site_plot,
    weekly_plot_site = EventWklySite,
    monthly_plot = Event_monthly_means_plot,
    monthly_plot_site = Event_monthly_means_site_plot
  )

  # Add strata plots if applicable
  if("Strata" %in% names(daily_site_summary)){
    save_list <- c(
      save_list,
      list(
        daily_plot_strata = Events_daily_strata_plot,
        weekly_plot_strata = EventWklyStrata,
        monthly_plot_strata = Event_monthly_means_stratum_plot,
        monthly_plot_strata_overlay = Event_monthly_means_stratum_plot_overlay
      )
    )
  }

  # Add vegetation class plots if applicable
  if("Vegetation Class" %in% names(daily_site_summary)){
    save_list <- c(
      save_list,
      list(
        daily_plot_veg = Events_daily_veg_plot,
        weekly_plot_veg = EventWklyVeg
      )
    )
  }

  # Write all plots into an .Rds file
  saveRDS(save_list, paste0(parent_dir,"/data_summaries/summary_plots/",proj_dep_name,"_saved_plots.Rds"))

  # Save each plot in the list as a separate PNG file
  for (plot_name in names(save_list)) {
    plot_data <- save_list[[plot_name]]$data
    if (is.data.frame(plot_data) && nrow(plot_data) == 0) {
      warning("Skipping PNG for plot with no data: ", plot_name)
    } else {
      data_description <- if (is.data.frame(plot_data)) paste(nrow(plot_data), "rows") else "layer-defined data"
      print(paste("Saving plot:", plot_name, "with", data_description))
      safe_ggsave(
        filename = paste0(parent_dir,"/data_summaries/summary_plots/",proj_dep_name,"_",plot_name,".png"),
        plot = save_list[[plot_name]],
        width = 10,
        height = 8
      )
    }
  }


  setwd(og_dir)
  print("Running data_summaries_function complete.")
  return("Finished!")

}


