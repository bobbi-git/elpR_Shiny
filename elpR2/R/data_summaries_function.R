#' @title Data Summaries
#' @author Bobbi J. Estabrook <bobbi.estabrook@cornell.edu>
#'
#' @description
#' This function summarizes data from the annotated selection tables, the sound check files, and the zero-days selection tables into hourly, daily, weekly, and monthly time periods.
#' The summaries will yield .txt files containing summary data and an .rds file containing plots.
#' This function will:
#' \itemize{
#' \item Install and load necessary packages
#' \item Read in data provided by the user (sound check files, random dates, selection tables, zero-day tables, sites file)
#' \item Generate summary tables and plots that are saved to /data_summaries/summary_tables and /data_summaries/summary_plots, respectively
#' }
#'
#' @param parent_dir Folder containing the specific elpR sub-folder structure
#' @param project_name Project name (e.g., PNNN, DzangaBai, Kakum)
#' @param deployment_num Deployment(s) number (e.g., 01-12, 04)
#' @param detector_name Detector used (e.g., HoriHarm, FruitPunchAI, Stanford Detector)
#' @param event_count_column Name of the input column containing event counts
#' @param selection_tables Folder containing selection tables
#' @param zero_txt Folder containing zero-days files generated by restrucutre_Event_function()
#' @param sound_check_include If you have sound check .xlsx files for this script to filter out bad sounds (y/n)
#' @param sound_checks Folder containing sound check .xlsx files
#' @param use_only_sites_provided If you want to include only the sites listed in a site_lat_long file (y/n)
#' @param site_lat_long A .txt file containing site names with latitude, longitude, vegetation class (optional), strata (optional): See existing files in the "elpR/Files/sites" folder for required structure of .txt file
#' @param rand_dates_needed If you want 3 random days per week (y/n) *dates are pre-selected in the /rand-days/Rand_dates.csv file
#' @param events_bad_sound_remove If you want to exclude sounds with less than 23 hrs of sound (y/n)
#'
#' @return
#' This function outputs:
#' \itemize{
#' \item Summary tables
#'  \itemize{
#'  \item Hourly summary tables include:
#'    \itemize{
#'    \item Site
#'    \item Date
#'    \item File Name
#'    \item Hour
#'    \item Deployment Number
#'    \item Sum Events
#'    \item Latitude
#'    \item Longitude
#'    \item Vegetation Class (if provided in sites file)
#'    \item Strata (if provided in sites file)
#'    \item Month
#'    \item Year
#'    \item WeekDate
#'    \item DayNight: If the hour is considered day (06:00 – 18:00) or night (18:00 – 06:00)
#'    }
#'  \item Daily summary tables include:
#'    \itemize{
#'    \item Date
#'    \item Site
#'    \item WeekDate
#'    \item Latitude
#'    \item Longitude
#'    \item Vegetation Class (if provided in sites file)
#'    \item Strata (if provided in sites file)
#'    \item total_Events
#'    \item n_hours: Total hours sampled for the date
#'    \item n_valid_hours: Total valid hours sampled for the date
#'    \item night_total: Total nighttime Events for the date
#'    \item prop_night: Proportion of nighttime Events to all Events for the date
#'    \item prop_day: Proportion of daytime Events to all Events for the date
#'    \item Month
#'    \item Year
#'    \item Week
#'    }
#'  \item Weekly summary tables include:
#'    \itemize{
#'    \item WeekDate
#'    \item Site/Strata/Vegetation Class
#'    \item Latitude
#'    \item Longitude
#'    \item Vegetation Class (if provided in sites file)
#'    \item Strata (if provided in sites file)
#'    \item MeanDailyEvents: Mean number of Events per day for the week
#'    \item sdDailyEvents: Standard deviation of the number of Events per day for the week
#'    \item n: Number of sampled days included in weekly calculations
#'    \item seDailyEvents: Standard error of the number of Events per day for the week
#'    \item maxDailyEvents: Maximum number of Events per day for the week
#'    \item minDailyEvents: Minimum number of Events per day for the week
#'    \item sumEvents: Total number of Events for the week
#'    \item sumEventsNight: Total number of nighttime Events for the week
#'    \item meanEventsNight: Mean number of nighttime Events for the week
#'    \item sdEventsNight: Standard deviation of the number of nighttime Events for the week
#'    \item seEventsNight: Standard error of the number of nighttime Events for the week
#'    \item PropNightEvents: Proportion of nighttime Events to all Events for the week
#'    \item SumEventsPerDaysSampled: Total daytime Events for the week
#'    \item SumNightEventsPerDaySampled: Nighttime Events divided by number of days per week
#'    }
#'  \item Monthly summary tables include:
#'    \itemize{
#'    \item Year
#'    \item Month
#'    \item MeanDailyEvents: Mean number of Events per day for the month
#'    \item sdDailyEvents: Standard deviation of the number of Events per day for the month
#'    \item n: Number of sampled days included in monthly calculations
#'    \item seDailyEvents: Standard error of the number of Events per day for the month
#'    \item maxDailyEvents: Maximum number of Events per day for the month
#'    \item minDailyEvents: Minimum number of Events per day for the month
#'    \item sumEvents: Total number of Events for the month
#'    \item sumNightEvents: Total number of nighttime Events for the month
#'    \item meanNightEvents: Mean number of nighttime Events for the month
#'    \item proportionNightEvents: Proportion of nighttime Events to all Events for the month
#'    \item Year-Month: WeekDate
#'    }
#' }
#' \item Summary plots
#'  \itemize{
#'  \item Plots saved in "saved_plots.Rds" include:
#'    \itemize{
#'    \item total_plot: Line plot of total Events per hour per site
#'    \item night_day_plot: Box plot of total daytime and nighttime Events for all sites
#'    \item hourly_plot: Bar plot of mean Events per hour for all sites
#'    \item daily_plot_site: Line plots of total Events per date by site
#'    \item daily_plot_strata: Line plots of total Events per date by strata (if strata is provided in sites file)
#'    \item daily_plot_veg: Line plots of total Events per date by vegetation class (if vegetation class is provided in sites file)
#'    \item weekly_plot_site: Line plots of mean number of daily Events per week per site
#'    \item weekly_plot_strata: Line plots of mean number of daily Events per week per strata (if strata provided in sites file)
#'    \item weekly_plot_veg: Line plots of mean number of daily Events per week per vegetation class (if vegetation class is provided in sites file)
#'    \item monthly_plot: Line plot of mean number of daily Events per month for all sites
#'    \item monthly_plot_site: Line plots of mean number of daily Events per month by site
#'    \item monthly_plot_strata: Line plots of mean number of daily Events per month by strata (if strata is provided in sites file)
#'    \item monthly_plot_strata_overlay: Line plots from monthly_plot_strata on the same graph
#'    }
#'  }
#' }
#'
#' @export

data_summaries_function <- function(
    parent_dir,
    project_name,
    deployment_num,
    detector_name,
    event_count_column,
    selection_tables,
    zero_txt,
    sound_check_include,
    sound_checks,
    use_only_sites_provided,
    site_lat_long,
    rand_dates_needed,
    events_bad_sound_remove
  ){

  print("Running data_summaries_function...")
  og_dir <- getwd() #to reset wd at the end of the function

    graphics.off()  # close all plot devices
    gc()            # collect garbage

    if(sound_check_include == "y"){
      print("you indicated that you have a sound_check file for this script to filter out bad sounds")
    } else {print("you indicated that you DO NOT have a sound_check file for this script to filter out bad sounds")
        }
    if(rand_dates_needed == "y"){
      print("you indicated that you would like to filter the selections by those that fall on a pre-selected random date")
    } else { print("you indicated that you DO NOT want to filter the selections by those that fall on a pre-selected random date. All dates will be included in results")
      }
    if(events_bad_sound_remove == "y"){
      print("you want to remove detections that occur on sound files with <23 hrs of sound")
    } else {print("you DO NOT want to remove detections that occur on sound files with <23 hrs of sound. Detections that occur on partial sound dates will be included in results")
        }
    if(use_only_sites_provided == "y"){
      print("you only want to include the sites that were listed in the site_lat_long file. This might result in detections being excluded if they occur on sites not included in the site_lat_long file")
    } else {print("you want to include all sites that are in the merged selection tables, and will not filter only by sites listed in the site_lat_long file.")
        }

  setwd(paste0(parent_dir, "/data_summaries"))

    # install and load necessary packages
    det_sum_packages <- c("shiny","dplyr", "tidyverse","stringr","purrr","lubridate","readxl","stargazer","broom","ggplot2")
      options(warn = -1)
    for (i in det_sum_packages){
      if (!require(i, quietly = TRUE, character.only = TRUE)){
        install.packages(i)
        library(i, character.only = TRUE)
      }
    }

   # Define helper to not kill function if saving fails
    safe_ggsave <- function(filename, plot, ...) {
      tryCatch(
        ggsave(filename, plot = plot, ...),
        error = function(e) {
          warning("ggsave failed for ", filename, ": ", conditionMessage(e))
        }
      )
    }

    normalize_detection_table <- function(table, event_count_column, file_path = NA_character_) {
      if (!(event_count_column %in% names(table))) {
        stop(
          "Selection table lacks the selected event-count column '",
          event_count_column,
          "': ",
          file_path
        )
      }
      if (event_count_column != "Count") {
        names(table)[names(table) == event_count_column] <- "Count"
      }
      table$Count <- as.numeric(table$Count)
      table$`File Offset (s)` <- as.numeric(table$`File Offset (s)`)
      table
    }

    # Make any error drop us into seeing where it came from
    options(error = rlang::entrace)  # requires rlang


  # file names
  proj_dep_name <-paste(project_name,"_dep",deployment_num,"_",detector_name,sep="") #default raw output table name

  #### LOAD IN ALL DATA ####

  ##### Sound Check Files #####
    # Should read in excel tables, not .txt files since those aren't frequently updated
    if(sound_check_include == "y"){
      sound_check_list <- list.files(path = sound_checks,
                                     recursive=T,
                                     full.names=TRUE,
                                     pattern = "*.xlsx") # list all the selection tables in the selection_tables folder
      #sound_check_list <- lapply(sound_check_list, function(x) {read.table(file = x, header = T, sep ="\t", check.names=FALSE,quote = "\"",comment.char = "")})  # Read the files in, assuming tab separator
      #sound_check_list <- rapply(sound_check_list, as.character, how = "replace") #make all columns character types before merging
      #sound_check_merge_df <- do.call("rbind", lapply(sound_check_list_df, as.data.frame)) # Combine them (the events cross over between sites and cuts off the last site - use the rbind.fill function)
      # sum(sapply(all_txt_df, nrow))
      sound_check_list_df <- lapply(sound_check_list, read_xlsx,
                                    sheet = "Sounds",
                                    col_names = TRUE)  # Read the files in
      sound_check_list_df <- lapply(sound_check_list_df, function(df) {
        if("SampleRate" %in% names(df)) {
          df$SampleRate <- as.numeric(as.character(df$SampleRate))
        }
        if ("Deployment Number" %in% names(df)) {
          df$`Deployment Number` <- as.numeric(as.character(df$`Deployment Number`))
        }
        return(df)
      })
      sound_check_merge_df <- dplyr::bind_rows(sound_check_list_df) # merge all sound check files together
      cols.nums <- c("Duration Hours",'File Duration (s)',"SampleRate")
      sound_check_merge_df[cols.nums] <- sapply(sound_check_merge_df[cols.nums],as.numeric) # set specific columns as numeric
      sound_check_merge_df$`File Start DateTime` <- as.POSIXct(str_extract(sound_check_merge_df$`Current File Name`,"\\d{8}.\\d{6}"),format='%Y%m%d_%H%M%S',origin = "1970-01-01",tz="Africa/Brazzaville") # convert the data and time charaters to real date and time with the correct time zone
      sound_check_merge_df$`File Start Date` <- format(as.Date(str_extract(sound_check_merge_df$'Current File Name' ,"\\d{8}.\\d{6}"),"%Y%m%d"),"%m/%d/%Y")
      sound_check_merge_df$`File End DateTime` <- sound_check_merge_df$`File Start DateTime`+ sound_check_merge_df$`File Duration (s)`
      sound_check_merge_df$`File End Date` <- format(as.Date(sound_check_merge_df$`File End DateTime`,"%Y%m%d",tz="Africa/Brazzaville"),"%m/%d/%Y")
      sound_check_merge_df$Detector <- "Sound Check"
      sound_check_merge_df$'Sound Check Count' <- "sound check"
      sound_check_merge_df <-dplyr::rename(sound_check_merge_df,`File Name` = `Current File Name`) # rename to, from
      #sound_check_merge_df <-rename(sound_check_merge_df,`Deployment Number` = `Deployment`) # rename to, from
      # Check if "Deployment" exists and "Deployment Number" doesn't
      if ("Deployment" %in% names(sound_check_merge_df) &&
          !("Deployment Number" %in% names(sound_check_merge_df))) {
        sound_check_merge_df <- dplyr::rename(sound_check_merge_df,
                                       `Deployment Number` = `Deployment`)
      }
      sound_check_merge_df$`Deployment Number` <- as.numeric(sound_check_merge_df$`Deployment Number`)
      sound_check_merge_df2 <- sound_check_merge_df[,c("Site", "File Name","File Duration (s)","File Start DateTime","File Start Date","File End DateTime",
                                                       "File End Date","Sound Check Count","Exclude (y/e)","Notes",
                                                       "Deployment Number")] # create new dataframe with specific columns
      sound_check_merge_df2 <- dplyr::rename(sound_check_merge_df2, "Date" = "File Start Date")
      sound_check_merge_df2$`File Start DateTime` <- as.POSIXct(str_extract(sound_check_merge_df2$'File Name',"\\d{8}.\\d{6}"),format='%Y%m%d_%H%M%S',origin = "1970-01-01",tz="Africa/Brazzaville") # convert the data and time charaters to real date and time with the correct time zone
      sound_check_merge_df2$`File Start Date` <- format(as.Date(str_extract(sound_check_merge_df2$'File Name' ,"\\d{8}.\\d{6}"),"%Y%m%d"),"%m/%d/%Y")
      sound_check_merge_df2$`File End DateTime` <- sound_check_merge_df2$`File Start DateTime`+ sound_check_merge_df2$`File Duration (s)`
      sound_check_merge_df2$`File End Date` <- format(as.Date(sound_check_merge_df2$`File End DateTime`,"%Y%m%d",tz="Africa/Brazzaville"),"%m/%d/%Y")
      sound_check_merge_df2$Hour <- hour(sound_check_merge_df2$`File Start DateTime`)
      sound_check_merge_df2$Date <- as.Date(sound_check_merge_df$`File Start Date`,format="%m/%d/%Y")
      sound_check_merge_df2$`Sound Check File` <-
      #View(sound_check_merge_df2)
      #names(sound_check_merge_df2)
      #dim(sound_check_merge_df2)
      #str(sound_check_merge_df2)
      #unique(sound_check_merge_df2$`Exclude (y/e)`, na.rm=T)
      write.table(sound_check_merge_df2,paste(parent_dir,"/data_summaries/summary_tables/",proj_dep_name,"_soundCheck_merged.txt",sep=""),sep='\t',na="",col.names=TRUE,row.names=FALSE, quote=FALSE, append=FALSE)
      print(paste("Minimum Sound Check Date",min(sound_check_merge_df2$'File Start DateTime', na.rm = TRUE),sep=" ")) # 2017-10-02 WAT
      print(paste("Maximum Sound Check Date",max(sound_check_merge_df2$'File Start DateTime', na.rm = TRUE),sep = " ")) # 2023-11-27 WAT
      print(paste("Total hours of sounds in this dataset:",round(sum(sound_check_merge_df2$`File Duration (s)`, na.rm=TRUE)/60/60, digits = 4),sep= " "))
      print(paste("Total years of sounds in this dataset:",round(sum(sound_check_merge_df2$`File Duration (s)`, na.rm=TRUE)/60/60/24/365, digits = 4),sep= " "))
    }


  ##### Rand Dates  #####
    #(3 random dates per week for event data, beginning in deployment 4)
    if(rand_dates_needed == "y"){
      elp_rand<-read.table(paste(parent_dir, '/rand-days/Rand_dates.csv', sep=""),header=TRUE,sep="\t",row.names=NULL) #read in rand file that contains 3 random days per week of the survey
      elp_rand$Date<-format(as.Date(elp_rand$Date,"%d-%b-%y"), "%m/%d/%Y") #tell R what the date structure is and read it as date and format the date to match Raven selection tables
      elp_rand$Date <- as.Date(elp_rand$Date,"%m/%d/%Y")
      elp_rand$"Rand"<-"rand" #create a column that is populated with "rand" to merge with the selection tables
    }

  ##### Selection Tables #####
  # (event detections (0+))
  selection_tables_list<-list.files(path = selection_tables,recursive=F,full.names=TRUE, pattern = "*.txt") # list all the selection tables in the selection_tables folder
  selection_tables_list <- lapply(selection_tables_list, function(x) {
    normalize_detection_table(
      read.table(file = x, header = T, sep ="\t", check.names=FALSE,quote = "\"",comment.char = "", fill=T),
      event_count_column = event_count_column,
      file_path = x
    )})  # Read and normalize the files
  #names(selection_tables_list) <- basename(selection_tables[c(1:6,8)]) # name the objects in list as the file names
  selection_tables_list <- rapply(selection_tables_list, as.character, how = "replace") #make all columns character types before merging
  events_merge_df <- dplyr::bind_rows(selection_tables_list) # merge all tables together
  #list2env(selection_tables_list ,.GlobalEnv)
  #names(events_merge_df)
  cols.num <- c("Count","Deployment Number",'File Offset (s)')
  events_merge_df[cols.num] <- lapply(events_merge_df[cols.num],as.numeric)
  events_merge_df$Site <- substr(str_match(events_merge_df$`Begin File`,"[a-zA-Z]{2}\\d{2}[a-zA-Z]{1}.")[,1],1,
                              nchar(str_match(events_merge_df$`Begin File`,"[a-zA-Z]{2}\\d{2}[a-zA-Z]{1}.")[,1])-1)
  #stem(as.numeric(events_merge_df$`Begin Hour`))
  #unique(events_merge_df$`Begin Hour`)

  events_dets_df <- events_merge_df[,c("Site", "Begin File","File Offset (s)","Count","Deployment Number","Sound Problems", "Notes")]
  events_dets_df$`File Start DateTime` <- as.POSIXct(str_extract(events_dets_df$`Begin File`,"\\d{8}.\\d{6}"),format='%Y%m%d_%H%M%S',origin = "1970-01-01",tz="Africa/Brazzaville") # convert the data and time charaters to real date and time with the correct time zone
  events_dets_df$`File Start Date` <- format(as.Date(str_extract(events_dets_df$'Begin File' ,"\\d{8}.\\d{6}"),"%Y%m%d"),"%m/%d/%Y")
  events_dets_df$`Detection DateTime` <- events_dets_df$`File Start DateTime`+ events_dets_df$`File Offset (s)`
  events_dets_df$`Date` <- as.Date(events_dets_df$`Detection DateTime`,"%Y%m%d",tz="Africa/Brazzaville")
  events_dets_df$Hour <- hour(events_dets_df$`Detection DateTime`)#format(as.POSIXct(events_dets_df$`Detection DateTime`), format = "%H") # get hour of selection
  events_dets_df$Detector <- detector_name
  events_dets_df <- dplyr::rename(events_dets_df, "File Name" = "Begin File")
  events_dets_df$Month <- month(events_dets_df$Date)
  events_dets_df$Year <- year(events_dets_df$Date)

  # View(events_dets_df)
  # dim(events_dets_df) #31854      13
  # stem(events_dets_df$Hour)
  # unique(events_dets_df$Hour)
  # names(events_dets_df)
  print(paste("Minimum Event selection table date:",min(events_dets_df$`File Start DateTime`, na.rm = TRUE),sep=" "))
  print(paste("Maximum Event selection table date:",max(events_dets_df$`File Start DateTime`, na.rm = TRUE),sep=" "))
  print(paste("Total detected Events:",sum(events_dets_df$Count, na.rm = TRUE),sep=" ")) # 2382 Events
  write.table(events_dets_df,paste(parent_dir,"/data_summaries/summary_tables/",proj_dep_name,"_events_SSTs_merged.txt",sep=""),sep='\t',na="",col.names=TRUE,row.names=FALSE, quote=FALSE, append=FALSE)


  ##### Zero-Days Tables  #####
  # selection tables with 0 hori-harm detections at filtered score threshold on rand dates
    if(exists(zero_txt)){
      zero_days<-list.files(path = zero_txt,recursive=T,full.names=TRUE, pattern = "*.txt") # list all the selection tables in the selection_tables folder
      zero_days_list <- lapply(zero_days, function(x) {
        normalize_detection_table(
          read.table(file = x, header = T, sep ="\t", check.names=FALSE,quote = "\"",comment.char = ""),
          event_count_column = event_count_column,
          file_path = x
        )})  # Read and normalize zero-day tables
      names(zero_days_list) <- basename(zero_days) # name the objects in list as the file names
      zero_days_df <- dplyr::bind_rows(zero_days_list) # merge all tables together
      zero_days_df$Rand <- ""
      #zero_days_df<- rename(zero_days_df, "Deployment Number" = "Deployment")
      #View(zero_days_df)
      #names(zero_days_df)

      zero_days_df2 <- zero_days_df[,c("Site", "Begin File","File Offset (s)","Count",
                                       "Deployment Number","Sound Problems", "Notes", "Rand")]
      #zero_days_df2 <- dplyr::rename(zero_days_df2, "Event Count" = "Count")
      zero_days_df2 <- dplyr::rename(zero_days_df2, "File Name" = "Begin File")
      zero_days_df2$'Count' <- 0
      zero_days_df2$`File Start DateTime` <- as.POSIXct(str_extract(zero_days_df2$`File Name`,"\\d{8}.\\d{6}"),format='%Y%m%d_%H%M%S',origin = "1970-01-01",tz="Africa/Brazzaville") # convert the data and time charaters to real date and time with the correct time zone
      zero_days_df2$`File Start Date` <- format(as.Date(str_extract(zero_days_df2$'File Name' ,"\\d{8}.\\d{6}"),"%Y%m%d"),"%m/%d/%Y")
      zero_days_df2$`Detection DateTime` <- zero_days_df2$`File Start DateTime`+ zero_days_df2$`File Offset (s)`
      zero_days_df2$`Date` <- as.Date(zero_days_df2$`Detection DateTime`,"%Y%m%d",tz="Africa/Brazzaville")
      zero_days_df2$`Hour` <- hour(zero_days_df2$`File Start DateTime`)
      zero_days_df2$Detector <- detector_name
    }

  #### Site information ####
    if(exists("site_lat_long")){
      site_info_names <- names(site_lat_long)
    }

  #### FILTER BY ANALYSIS DATES ####

  #create table for every hour from the first to last in detector files
  # combing events and zero days
    if(exists(zero_txt)){
      events_dets_df_zero <- full_join(events_dets_df,zero_days_df2)
      print(paste("Total Events in merged table:",sum(events_dets_df_zero$Count,na.rm=T), sep = " ")) # 2382
      print(paste("Min date in merged table:",min(events_dets_df_zero$Date), sep = " "))
      print(paste("Max date in merged table:",max(events_dets_df_zero$Date), sep = " "))
    } else {
      events_dets_df_zero <- events_dets_df
    }
  # stem(events_dets_df_zero$Hour)
  # events_dets_df_zero$Month <- month(events_dets_df_zero$Date)
  # events_dets_df_zero$Year <- year(events_dets_df_zero$Date)


  # add sound check (if user requested)
    if(events_bad_sound_remove == "y"| sound_check_include == "y"){
           events_dets_df_zero <- full_join(events_dets_df_zero,sound_check_merge_df2) # merge det df with sound check
           events_dets_df_zero <- events_dets_df_zero %>%
             filter(is.na(`Exclude (y/e)`) | !(`Exclude (y/e)` %in% c("y", "Y","e")))
          }
  # sum(events_dets_df_zero$`Event Count`, na.rm = T)
  # unique(events_dets_df_zero$`Exclude (y/e)`,na.rm=T)

  # add rand dates (if user requested) and remove detections on non rand dates if requested
